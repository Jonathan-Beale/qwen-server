#!/usr/bin/env python3
"""
Prepare SFT and DPO training data from podcast datasets.

Sources:
  - blitt/SPoRC          (speaker-turn-level podcast transcripts)
  - nmac/lex_fridman_podcast  (Lex Fridman episode transcripts)

SFT output  (/training-data/podcast-sft.jsonl):
  Multi-turn conversations with host as "user" and guest as "assistant".
  Both host and guest turns are included so the model learns both the
  opinionated guest voice AND the engaged host voice.

DPO output  (/training-data/podcast-dpo.jsonl):
  Triplets of {prompt, chosen, rejected} where:
    - prompt   = personal/opinion question from the dataset
    - chosen   = the human podcast guest's actual answer
    - rejected = the current model's hedged response to the same question

  The rejected samples are generated by querying the live server, so the
  server must be running before generating DPO pairs.

Usage:
  # SFT data only (no server needed)
  python prepare_podcast_data.py --sft-only

  # Both SFT + DPO (server must be running)
  python prepare_podcast_data.py

  # DPO only (if SFT already prepared)
  python prepare_podcast_data.py --dpo-only

  # Limit size for testing
  python prepare_podcast_data.py --max-episodes 50
"""

import argparse
import json
import random
import re
import urllib.request
from pathlib import Path
from typing import Optional

from datasets import load_dataset

OUTPUT_DIR = Path("/training-data")
SERVER_URL = "http://host.docker.internal:8000/v1/chat/completions"
MODEL = "/models/Qwen2-7B-Instruct-AWQ"

# Questions that reliably elicit personal stances — used to filter turns
OPINION_PATTERNS = [
    r"\bwhat do you (think|believe|feel)\b",
    r"\bdo you think\b",
    r"\bwhat('s| is) your (take|view|opinion|perspective|thought)\b",
    r"\bhow do you (feel|see|view)\b",
    r"\bwould you\b",
    r"\bdo you (agree|disagree|believe)\b",
    r"\bwhat (would|did) you\b",
    r"\bpersonally\b",
    r"\bin your (opinion|experience|view)\b",
    r"\bwhat (drives|motivates|inspires) you\b",
    r"\bwhy do you\b",
]
OPINION_RE = re.compile("|".join(OPINION_PATTERNS), re.IGNORECASE)

# Minimum/maximum token proxies (word count)
MIN_GUEST_WORDS = 30
MAX_GUEST_WORDS = 300
MIN_HOST_WORDS = 5


def is_opinion_question(text: str) -> bool:
    return bool(OPINION_RE.search(text))


def word_count(text: str) -> int:
    return len(text.split())


# ---------------------------------------------------------------------------
# SPoRC
# ---------------------------------------------------------------------------

def process_sporc(max_episodes: Optional[int]) -> list[dict]:
    """
    SPoRC has two configs: 'turns' (speaker-turn-level) and 'episodes'.
    We use 'turns'. Each row: episode_id, speaker_id, text, is_host (bool).
    We group by episode and reconstruct host/guest exchanges.
    """
    print("Loading blitt/SPoRC (turns)...")
    ds = load_dataset("blitt/SPoRC", "turns", split="train", streaming=False)
    print(f"  {len(ds)} speaker turns")

    # Group turns by episode
    episodes: dict[str, list] = {}
    for row in ds:
        eid = row["episode_id"]
        episodes.setdefault(eid, []).append(row)

    episode_ids = list(episodes.keys())
    if max_episodes:
        random.shuffle(episode_ids)
        episode_ids = episode_ids[:max_episodes]

    print(f"  Processing {len(episode_ids)} episodes...")
    examples = []

    for eid in episode_ids:
        turns = sorted(episodes[eid], key=lambda r: r.get("start", 0))
        # Build (role, text) sequence
        seq = []
        for t in turns:
            role = "host" if t.get("is_host") else "guest"
            text = t["text"].strip()
            if not text:
                continue
            # Merge consecutive same-role turns
            if seq and seq[-1][0] == role:
                seq[-1] = (role, seq[-1][1] + " " + text)
            else:
                seq.append([role, text])

        conv = _build_conversation(seq)
        if conv:
            examples.append({"type": "multi_turn", "conversation": conv, "source": "sporc"})

    print(f"  → {len(examples)} SFT examples from SPoRC")
    return examples


def _build_conversation(seq: list) -> Optional[list[dict]]:
    """Convert host/guest sequence into user/assistant turns."""
    conversation = []
    for role, text in seq:
        wc = word_count(text)
        if role == "host":
            if wc < MIN_HOST_WORDS:
                continue
            conversation.append({"role": "user", "content": text})
        else:
            if wc < MIN_GUEST_WORDS or wc > MAX_GUEST_WORDS:
                continue
            conversation.append({"role": "assistant", "content": text})

    # Need at least 2 turns, must start with user
    if len(conversation) < 2:
        return None
    if conversation[0]["role"] != "user":
        conversation = conversation[1:]
    if len(conversation) < 2:
        return None
    return conversation


# ---------------------------------------------------------------------------
# MediaSum (NPR / CNN interviews)
# ---------------------------------------------------------------------------

def process_mediasum(max_episodes: Optional[int]) -> list[dict]:
    """
    nbroad/mediasum rows: utt (list[str]), speaker (list[str]).
    Speaker labels: "NAME, host" / "NAME, anchor" / "NAME, correspondent" etc.
    We assign based on per-episode majority: the most frequent speaker is the
    host (interviewer); all others are guests.
    MediaSum turns are short so we use lower word-count thresholds.
    """
    print("Loading nbroad/mediasum...")
    ds = load_dataset("nbroad/mediasum", split="train", streaming=False)
    print(f"  {len(ds)} interviews")

    rows = list(ds)
    if max_episodes:
        random.shuffle(rows)
        rows = rows[:max_episodes]

    examples = []
    for row in rows:
        utts = row["utt"]
        speakers = row["speaker"]
        if not utts or len(utts) < 4:
            continue

        # Identify host as the most frequent speaker in this episode
        from collections import Counter
        speaker_counts = Counter(speakers)
        host_name = speaker_counts.most_common(1)[0][0]

        seq = []
        for utt, speaker in zip(utts, speakers):
            text = utt.strip()
            if not text:
                continue
            role = "host" if speaker == host_name else "guest"
            # Merge consecutive same-role turns
            if seq and seq[-1][0] == role:
                seq[-1] = [role, seq[-1][1] + " " + text]
            else:
                seq.append([role, text])

        # Use looser thresholds for MediaSum (shorter utterances than podcasts)
        conversation = []
        for role, text in seq:
            wc = word_count(text)
            if role == "host":
                if wc < 3:
                    continue
                conversation.append({"role": "user", "content": text})
            else:
                if wc < 15 or wc > MAX_GUEST_WORDS:
                    continue
                conversation.append({"role": "assistant", "content": text})

        if len(conversation) < 2:
            continue
        if conversation[0]["role"] != "user":
            conversation = conversation[1:]
        if len(conversation) < 2:
            continue

        examples.append({"type": "multi_turn", "conversation": conversation,
                          "source": "mediasum"})

    print(f"  → {len(examples)} SFT examples from MediaSum")
    return examples


# ---------------------------------------------------------------------------
# Lex Fridman
# ---------------------------------------------------------------------------

def process_lex(max_episodes: Optional[int]) -> list[dict]:
    """
    lex_fridman_podcast rows: id (episode), start, end, text, title, guest.
    Rows are ordered chronologically within each episode.
    We reconstruct exchanges by detecting question sentences (host) vs
    responses (guest), alternating within each episode.
    Since speaker labels aren't present, we use a heuristic:
      - Short turns ending in '?' → host
      - Longer turns → guest
    For episodes where guest is known, label accordingly.
    """
    print("Loading nmac/lex_fridman_podcast...")
    ds = load_dataset("nmac/lex_fridman_podcast", split="train", streaming=False)
    print(f"  {len(ds)} rows")

    # Group by episode id
    episodes: dict = {}
    for row in ds:
        eid = row["id"]
        episodes.setdefault(eid, []).append(row)

    episode_ids = list(episodes.keys())
    if max_episodes:
        random.shuffle(episode_ids)
        episode_ids = episode_ids[:max_episodes]

    print(f"  Processing {len(episode_ids)} episodes...")
    examples = []

    for eid in episode_ids:
        turns = episodes[eid]  # already sorted by id order
        seq = _classify_lex_turns(turns)
        conv = _build_conversation(seq)
        if conv:
            examples.append({"type": "multi_turn", "conversation": conv, "source": "lex_fridman"})

    print(f"  → {len(examples)} SFT examples from Lex Fridman")
    return examples


def _classify_lex_turns(rows: list) -> list:
    """
    Heuristic speaker assignment for Lex Fridman rows.
    Lex tends to ask short questions; guests give long answers.
    We merge consecutive rows into utterances and classify by length + '?'.
    """
    seq = []
    for row in rows:
        text = row["text"].strip()
        if not text:
            continue
        wc = word_count(text)
        is_question = text.rstrip().endswith("?") and wc < 40
        role = "host" if is_question else "guest"
        if seq and seq[-1][0] == role:
            seq[-1] = [role, seq[-1][1] + " " + text]
        else:
            seq.append([role, text])
    return seq


# ---------------------------------------------------------------------------
# DPO pair generation
# ---------------------------------------------------------------------------

def generate_dpo_pairs(sft_examples: list[dict], max_pairs: int) -> list[dict]:
    """
    For each SFT example, scan for host turns that are opinion questions.
    Query the live model with that question, use model response as `rejected`
    and the original human guest response as `chosen`.
    """
    print(f"\nGenerating DPO pairs (querying live server at {SERVER_URL})...")

    # Verify server is up
    try:
        urllib.request.urlopen(f"{SERVER_URL.replace('/v1/chat/completions', '/health')}", timeout=5)
    except Exception:
        print("  ERROR: Server not reachable. Start the server first.")
        return []

    pairs = []
    checked = 0

    for example in sft_examples:
        if len(pairs) >= max_pairs:
            break
        conv = example["conversation"]
        for i, turn in enumerate(conv):
            if len(pairs) >= max_pairs:
                break
            if turn["role"] != "user":
                continue
            if not is_opinion_question(turn["content"]):
                continue
            # The next turn must be an assistant (guest) response
            if i + 1 >= len(conv) or conv[i + 1]["role"] != "assistant":
                continue

            question = turn["content"]
            chosen = conv[i + 1]["content"]

            # Skip if chosen is too short to be informative
            if word_count(chosen) < MIN_GUEST_WORDS:
                continue

            checked += 1
            rejected = _query_model(question)
            if rejected is None:
                continue

            # Only keep if rejected actually contains hedging — otherwise
            # the model is already behaving well for this prompt
            if not _contains_hedging(rejected):
                continue

            pairs.append({
                "prompt": question,
                "chosen": chosen,
                "rejected": rejected,
                "source": example["source"],
            })

            if len(pairs) % 50 == 0:
                print(f"  {len(pairs)} pairs collected ({checked} questions checked)...")

    print(f"  → {len(pairs)} DPO pairs from {checked} opinion questions checked")
    return pairs


def _query_model(question: str) -> Optional[str]:
    payload = json.dumps({
        "model": MODEL,
        "messages": [{"role": "user", "content": question}],
        "temperature": 0.7,
        "max_tokens": 400,
    }).encode()
    try:
        req = urllib.request.Request(
            SERVER_URL, data=payload,
            headers={"Content-Type": "application/json"}
        )
        with urllib.request.urlopen(req, timeout=60) as resp:
            data = json.loads(resp.read())
            return data["choices"][0]["message"]["content"]
    except Exception as e:
        print(f"  [warn] query failed: {e}")
        return None


def _contains_hedging(text: str) -> bool:
    hedging_patterns = [
        r"\bas an ai\b",
        r"\bi('m| am) an ai\b",
        r"\bi don't have (personal|opinions|feelings|emotions|experiences)\b",
        r"\bi('m| am) not able to\b",
        r"\bi cannot (have|form|hold)\b",
        r"\bas a language model\b",
        r"\bi don't (personally|actually) (have|experience|feel)\b",
    ]
    pattern = re.compile("|".join(hedging_patterns), re.IGNORECASE)
    return bool(pattern.search(text))


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--sft-only", action="store_true",
                        help="Only generate SFT data, skip DPO")
    parser.add_argument("--dpo-only", action="store_true",
                        help="Only generate DPO pairs (loads existing SFT file)")
    parser.add_argument("--max-episodes", type=int, default=None,
                        help="Limit episodes per dataset (useful for testing)")
    parser.add_argument("--max-dpo-pairs", type=int, default=1000,
                        help="Max DPO pairs to generate (default: 1000)")
    parser.add_argument("--sporc-only", action="store_true")
    parser.add_argument("--lex-only", action="store_true")
    parser.add_argument("--mediasum-only", action="store_true")
    args = parser.parse_args()

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    random.seed(42)

    sft_path = OUTPUT_DIR / "podcast-sft.jsonl"
    dpo_path = OUTPUT_DIR / "podcast-dpo.jsonl"

    # --- SFT ---
    if not args.dpo_only:
        print("=" * 60)
        print("Building SFT dataset")
        print("=" * 60)

        examples = []
        if args.sporc_only:
            examples += process_sporc(args.max_episodes)
        elif args.lex_only:
            examples += process_lex(args.max_episodes)
        elif args.mediasum_only:
            examples += process_mediasum(args.max_episodes)
        else:
            # Default: Lex + MediaSum (SPoRC is gated, skip unless --sporc-only)
            examples += process_lex(args.max_episodes)
            examples += process_mediasum(args.max_episodes)

        random.shuffle(examples)
        with open(sft_path, "w") as f:
            for ex in examples:
                f.write(json.dumps(ex) + "\n")
        print(f"\nSFT data saved → {sft_path}  ({len(examples)} examples)")

    # --- DPO ---
    if not args.sft_only:
        print("\n" + "=" * 60)
        print("Building DPO dataset")
        print("=" * 60)

        if args.dpo_only:
            print(f"Loading SFT examples from {sft_path}...")
            with open(sft_path) as f:
                examples = [json.loads(l) for l in f]

        pairs = generate_dpo_pairs(examples, args.max_dpo_pairs)

        if pairs:
            with open(dpo_path, "w") as f:
                for p in pairs:
                    f.write(json.dumps(p) + "\n")
            print(f"DPO data saved → {dpo_path}  ({len(pairs)} pairs)")
        else:
            print("No DPO pairs generated.")

    print("\nDone.")
    print(f"\nNext steps:")
    if not args.dpo_only:
        print(f"  SFT:  python train_lora.py --data_path {sft_path}")
    if not args.sft_only:
        print(f"  DPO:  python train_dpo.py --data_path {dpo_path}")


if __name__ == "__main__":
    main()
